#!/usr/bin/env bash
# Week 17, activity 2: the observability stack (self-hosted Langfuse v4 + OpenTelemetry Collector).
# Idempotent: running it again duplicates nothing. The secrets are generated once in .secretos.env (chmod 600,
# ignored by Git) and are NEVER printed. The images are pulled by digest from ../preparar/versiones.json.
#
#   ./arrancar.sh              starts it (or confirms it is already running) and waits until everything responds
#   ./arrancar.sh --estado     shows the containers and the health of Langfuse and the Collector
#   ./arrancar.sh --detener    stops the containers (keeps volumes and data)
#   ./arrancar.sh --reiniciar  stops and starts again (the data persists)
#   ./arrancar.sh --muestreo   starts with tail sampling (errors, unanswered and slow tasks are kept; the rest at 10 %)
#   ./arrancar.sh --borrar     deletes containers, volumes, the network and datos/ (keeps .secretos.env)
#   ./arrancar.sh --borrar --secretos   the same, plus .secretos.env (the next start generates new keys)
set -euo pipefail

DIR="$(cd "$(dirname "$0")" && pwd)"
SECRETOS="$DIR/.secretos.env"
DATOS="$DIR/datos"
VERSIONES="$DIR/../preparar/versiones.json"
PROYECTO=s17-observabilidad
PUERTOS="3100 4317 4318 13133"
LANGFUSE=http://127.0.0.1:3100
COLLECTOR_SALUD=http://127.0.0.1:13133

uso() { sed -n '2,12p' "$0" | sed 's/^# \{0,1\}//' >&2; exit 2; }

accion=arrancar
con_secretos=no
con_muestreo=no
for a in "$@"; do
  case "$a" in
    --estado) accion=estado ;;
    --detener) accion=detener ;;
    --reiniciar) accion=reiniciar ;;
    --muestreo) con_muestreo=si ;;
    --borrar) accion=borrar ;;
    --secretos) con_secretos=si ;;
    -h|--help) uso ;;
    *) echo "unknown option: $a" >&2; uso ;;
  esac
done
if [[ "$con_muestreo" == si && "$accion" != arrancar && "$accion" != reiniciar ]]; then echo "--muestreo is only used when starting or restarting" >&2; exit 2; fi
if [[ "$con_muestreo" == si ]]; then export COLLECTOR_CAPA=muestreo; else export COLLECTOR_CAPA=sin_muestreo; fi
if [[ "$con_secretos" == si && "$accion" != borrar ]]; then echo "--secretos is only used with --borrar" >&2; exit 2; fi

command -v docker >/dev/null || { echo "[stack] Docker is missing" >&2; exit 1; }
command -v openssl >/dev/null || { echo "[stack] openssl is missing (it generates the secrets)" >&2; exit 1; }

# $1 = random bytes; prints 2*$1 hexadecimal characters
aleatorio() { openssl rand -hex "$1"; }

generar_secretos() {
  ( umask 077
    pk="pk-lf-$(aleatorio 8)"; sk="sk-lf-$(aleatorio 16)"
    {
      echo "# Generated by arrancar.sh on $(date -u +%FT%TZ). Do not commit."
      echo "POSTGRES_PASSWORD=$(aleatorio 16)"
      echo "CLICKHOUSE_PASSWORD=$(aleatorio 16)"
      echo "MINIO_ROOT_PASSWORD=$(aleatorio 16)"
      echo "REDIS_AUTH=$(aleatorio 16)"
      echo "SALT=$(aleatorio 16)"
      echo "ENCRYPTION_KEY=$(aleatorio 32)"
      echo "NEXTAUTH_SECRET=$(aleatorio 16)"
      echo "LANGFUSE_USER_PASSWORD=$(aleatorio 12)"
      echo "LANGFUSE_PUBLIC_KEY=$pk"
      echo "LANGFUSE_SECRET_KEY=$sk"
      echo "LANGFUSE_AUTH=$(printf '%s:%s' "$pk" "$sk" | base64 | tr -d '\n')"
    } >"$SECRETOS" )
  chmod 600 "$SECRETOS"
  echo "[stack] new secrets in .secretos.env ($(grep -c '=' "$SECRETOS") variables, mode 600; not printed)"
}

# Exports IMG_*: repository@digest from versiones.json (the tag is dropped: the digest is what is pinned).
cargar_imagenes() {
  local lineas linea
  lineas="$(python3 - "$VERSIONES" <<'PY'
import json, sys
v = json.load(open(sys.argv[1], encoding="utf-8"))
mapa = {"langfuse-web": "IMG_LANGFUSE_WEB", "langfuse-worker": "IMG_LANGFUSE_WORKER", "clickhouse": "IMG_CLICKHOUSE",
        "minio": "IMG_MINIO", "redis": "IMG_REDIS", "postgres": "IMG_POSTGRES", "otel-collector": "IMG_COLLECTOR"}
for nombre, var in mapa.items():
    print(f"{var}={v['imagenes'][nombre].rsplit(':', 1)[0]}@{v['digests'][nombre]}")
PY
)"
  while IFS= read -r linea; do export "$linea"; done <<<"$lineas"
}

if [[ -f "$SECRETOS" ]]; then ENVFILE="$SECRETOS"; chmod 600 "$SECRETOS"; else ENVFILE=/dev/null; fi
if [[ ! -f "$SECRETOS" && ( "$accion" == arrancar || "$accion" == reiniciar ) ]]; then
  generar_secretos; ENVFILE="$SECRETOS"
fi
cargar_imagenes
export HOST_UID="$(id -u)" HOST_GID="$(id -g)"
compose() { docker compose -p "$PROYECTO" -f "$DIR/docker-compose.yml" --env-file "$ENVFILE" "$@"; }
hay_contenedores() { [[ -n "$(docker ps -aq --filter "label=com.docker.compose.project=$PROYECTO")" ]]; }

revisar_puertos() {
  hay_contenedores && return 0                 # the stack's own containers hold them
  local p ocupados=""
  for p in $PUERTOS; do nc -z 127.0.0.1 "$p" >/dev/null 2>&1 && ocupados="$ocupados $p"; done
  if [[ -n "$ocupados" ]]; then echo "[stack] ports in use:$ocupados (another lab service?)" >&2; exit 3; fi
}

esperar() {
  local t0=$SECONDS
  echo -n "[stack] waiting for Langfuse (3100) and the Collector (13133) "
  until curl -fsS -o /dev/null "$LANGFUSE/api/public/health" 2>/dev/null && curl -fsS -o /dev/null "$COLLECTOR_SALUD/" 2>/dev/null; do
    if (( SECONDS - t0 > 300 )); then echo " no response within 300 s" >&2; compose ps >&2; exit 1; fi
    echo -n "."; sleep 3
  done
  echo " ready in $((SECONDS - t0)) s"
}

arrancar() {
  revisar_puertos
  mkdir -p "$DATOS"
  compose up -d --quiet-pull
  esperar
  echo "[stack] Langfuse:   $LANGFUSE (user admin@lab.example; password and project keys in .secretos.env)"
  echo "[stack] OTLP HTTP:  http://127.0.0.1:4318/v1/traces   OTLP gRPC: 127.0.0.1:4317   health: $COLLECTOR_SALUD"
  echo "[stack] tail sampling: $([[ "$con_muestreo" == si ]] && echo on || echo 'off (everything is kept)')"
  echo "[stack] traces (already redacted): $DATOS/trazas.jsonl"
}

borrar() {
  compose down -v --remove-orphans
  rm -rf "$DATOS"
  [[ "$con_secretos" == si ]] && rm -f "$SECRETOS"
  local c v r
  c="$(docker ps -aq --filter "label=com.docker.compose.project=$PROYECTO" | wc -l | tr -d ' ')"
  v="$(docker volume ls -q --filter "label=com.docker.compose.project=$PROYECTO" | wc -l | tr -d ' ')"
  r="$(docker network ls -q --filter "label=com.docker.compose.project=$PROYECTO" | wc -l | tr -d ' ')"
  echo "[stack] left after deleting: $c containers, $v volumes, $r networks; datos/ $([[ -e "$DATOS" ]] && echo exists || echo deleted)"
  [[ "$c$v$r" == 000 && ! -e "$DATOS" ]] || { echo "[stack] the deletion was not complete" >&2; exit 1; }
}

case "$accion" in
  arrancar) arrancar ;;
  reiniciar) compose stop; arrancar ;;
  detener) compose stop ;;
  borrar) borrar ;;
  estado)
    compose ps
    echo "Langfuse /api/public/health: $(curl -s -o /dev/null -w '%{http_code}' "$LANGFUSE/api/public/health" || true)"
    echo "Collector health_check:      $(curl -s -o /dev/null -w '%{http_code}' "$COLLECTOR_SALUD/" || true)" ;;
esac
