#!/usr/bin/env bash
# Week 14, activity 4: starts Keycloak with the legacybridge realm and sets the test users' passwords.
# Idempotent: running it again duplicates nothing (the realm is only imported if it does not exist; the passwords are
# set again to the same values). The secrets are generated once in .secretos.env (chmod 600, ignored by Git).
#
#   ./arrancar.sh             starts it (or confirms it is already running) and configures it
#   ./arrancar.sh --detener   stops the container (keeps the data)
#   ./arrancar.sh --borrar    stops it and deletes the volume (the next start re-imports the realm)
#
# KC_MODO=externo uses a Keycloak already running at $KC_URL and $KCADM (the path to kcadm.sh) instead of Docker.
set -euo pipefail
DIR="$(cd "$(dirname "$0")" && pwd)"
SECRETOS="$DIR/.secretos.env"
COMPOSE=(docker compose -f "$DIR/docker-compose.yml" --env-file "$SECRETOS")
KC_URL="${KC_URL:-http://127.0.0.1:8180}"
REALM=legacybridge
MODO="${KC_MODO:-docker}"
USUARIOS=(analista almacenista vendedor)

aleatorio() { LC_ALL=C tr -dc 'A-Za-z0-9' </dev/urandom | head -c 24; }

if [[ ! -f "$SECRETOS" ]]; then
  umask 077
  {
    echo "# Generated by arrancar.sh on $(date -u +%FT%TZ). Do not commit."
    echo "KC_BOOTSTRAP_ADMIN_USERNAME=admin"
    echo "KC_BOOTSTRAP_ADMIN_PASSWORD=$(aleatorio)"
    for u in "${USUARIOS[@]}"; do echo "KC_PWD_$(echo "$u" | tr '[:lower:]' '[:upper:]')=$(aleatorio)"; done
  } >"$SECRETOS"
  echo "[auth] new secrets in $SECRETOS"
fi
chmod 600 "$SECRETOS"
set -a; source "$SECRETOS"; set +a

case "${1:-}" in
  --detener|--stop) "${COMPOSE[@]}" stop; exit 0 ;;
  --borrar|--delete) "${COMPOSE[@]}" down -v; exit 0 ;;
  "") ;;
  *) echo "usage: $0 [--detener|--stop|--borrar|--delete]" >&2; exit 2 ;;
esac

if [[ "$MODO" == docker ]]; then
  "${COMPOSE[@]}" up -d --quiet-pull
  KCADM=("${COMPOSE[@]}" exec -T keycloak /opt/keycloak/bin/kcadm.sh)
  KCADM_SERVER=http://localhost:8080
  KCADM_CONFIG=/tmp/kcadm.config            # inside the container
else
  : "${KCADM:?with KC_MODO=externo, set KCADM=/path/to/kcadm.sh}"
  KCADM=("$KCADM")
  KCADM_SERVER="$KC_URL"
  KCADM_CONFIG="$(mktemp)"; trap 'rm -f "$KCADM_CONFIG"' EXIT
fi

echo -n "[auth] waiting for Keycloak at $KC_URL "
for _ in $(seq 1 90); do
  if curl -fsS "$KC_URL/realms/$REALM/.well-known/openid-configuration" >/dev/null 2>&1; then echo " ready"; break; fi
  echo -n "."; sleep 2
done
curl -fsS "$KC_URL/realms/$REALM/.well-known/openid-configuration" >/dev/null || { echo " no response" >&2; exit 1; }

kc() { "${KCADM[@]}" "$@" --config "$KCADM_CONFIG"; }
kc config credentials --server "$KCADM_SERVER" --realm master \
   --user "$KC_BOOTSTRAP_ADMIN_USERNAME" --password "$KC_BOOTSTRAP_ADMIN_PASSWORD" >/dev/null 2>&1
for u in "${USUARIOS[@]}"; do
  var="KC_PWD_$(echo "$u" | tr '[:lower:]' '[:upper:]')"
  kc set-password -r "$REALM" --username "$u" --new-password "${!var}"
done
recurso=$(kc get clients -r "$REALM" -q clientId=legado-mcp --fields 'attributes(resource_url)' | grep -o '"resource_url" *: *"[^"]*"' || true)
echo "[auth] realm $REALM ready: ${#USUARIOS[@]} users with a password; $recurso"
echo "[auth] issuer: $KC_URL/realms/$REALM  (passwords in $SECRETOS)"
